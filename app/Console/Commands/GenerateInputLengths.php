<?php

namespace App\Console\Commands;

use Illuminate\Console\Command;
use Illuminate\Support\Facades\DB;

/**
 * Writes public/js/input-lengths.js: for every table, its columns and the length of each text column.
 * public/js/input-maxlength.js uses it to put maxlength on form inputs. Run it after a schema change.
 */
class GenerateInputLengths extends Command
{
    protected $signature = 'inputs:lengths';

    protected $description = 'Regenerate the column-length map used to set maxlength on inputs';

    private const SKIP = ['migrations', 'failed_jobs', 'job_batches', 'sessions', 'cache', 'cache_locks', 'password_reset_tokens', 'personal_access_tokens', 'email_queues', 'email_verification_otps'];

    public function handle(): int
    {
        $rows = DB::select(
            'select table_name t, column_name c, data_type d, character_maximum_length l, numeric_precision np, numeric_scale ns from information_schema.columns where table_schema = ? order by table_name, ordinal_position',
            [DB::getDatabaseName()]
        );

        // is the table called `jobs` the framework queue table (columns queue + payload)?
        $queueJobs = \Illuminate\Support\Facades\Schema::hasTable('jobs') && \Illuminate\Support\Facades\Schema::hasColumn('jobs', 'payload') && \Illuminate\Support\Facades\Schema::hasColumn('jobs', 'queue');

        $tables = [];
        $any = [];
        $unbounded = [];
        $anyNum = [];
        foreach ($rows as $r) {
            $t = $r->t ?? $r->T;
            $c = $r->c ?? $r->C;
            $d = strtolower($r->d ?? $r->D);
            $l = (int) ($r->l ?? $r->L ?? 0);
            if (in_array($t, self::SKIP, true) || str_ends_with($t, '_old')) {
                continue;
            }
            // Laravel's queue table is also called `jobs`; here `jobs` holds the shipments, so only the queue-shaped one is skipped
            if ($t === 'jobs' && isset($queueJobs) && $queueJobs) {
                continue;
            }
            $isChar = in_array($d, ['varchar', 'char'], true);
            $num = $this->numericSpec($d, (int) ($r->np ?? $r->NP ?? 0), (int) ($r->ns ?? $r->NS ?? 0));
            // number: text length for a text column; "i:<digits>" / "d:<integer digits>:<decimals>" for a numeric one;
            // 0 = the column exists but nothing is limited (dates, long text, floats)
            $tables[$t][$c] = $isChar ? $l : ($num ?? 0);
            if ($num !== null) {
                $anyNum[$c] = $this->widest($anyNum[$c] ?? null, $num);
            }
            if ($isChar) {
                $any[$c] = max($any[$c] ?? 0, $l);
            } elseif (in_array($d, ['text', 'mediumtext', 'longtext', 'json'], true)) {
                $unbounded[$c] = true;
            }
        }
        // a name that is long text in any table is never limited by name alone
        foreach (array_keys($unbounded) as $c) {
            unset($any[$c]);
        }

        $json = json_encode(['tables' => $tables, 'any' => $any, 'anyNum' => $anyNum], JSON_UNESCAPED_SLASHES);
        file_put_contents(public_path('js/input-lengths.js'), "/* Generated by: php artisan inputs:lengths (do not edit) */\nwindow.__inputLengths = $json;\n");
        $this->info(count($tables) . ' tables, ' . count($any) . ' text column names written to public/js/input-lengths.js');

        return self::SUCCESS;
    }

    /** Digits a numeric column can hold, as a short spec the number boxes understand; null when it is not a bounded number. */
    private function numericSpec(string $type, int $precision, int $scale): ?string
    {
        // one digit less than the real maximum for int/bigint so a typed value can never overflow the column
        $digits = ['tinyint' => 3, 'smallint' => 5, 'mediumint' => 7, 'int' => 9, 'integer' => 9, 'bigint' => 18];
        if (isset($digits[$type])) {
            return 'i:' . $digits[$type];
        }
        if (in_array($type, ['decimal', 'numeric'], true) && $precision > 0) {
            return 'd:' . max(1, $precision - $scale) . ':' . $scale;
        }

        return null;
    }

    /** The more generous of two specs, for a name that exists in several tables. */
    private function widest(?string $a, string $b): string
    {
        if ($a === null) {
            return $b;
        }
        $pa = explode(':', $a);
        $pb = explode(':', $b);
        $digits = max((int) $pa[1], (int) $pb[1]);
        $dec = max((int) ($pa[2] ?? 0), (int) ($pb[2] ?? 0));

        return ($dec > 0 || $pa[0] === 'd' || $pb[0] === 'd') ? "d:$digits:$dec" : "i:$digits";
    }
}
